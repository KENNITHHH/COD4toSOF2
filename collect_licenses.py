"""collect_licenses.py - gather the licence texts of everything the .exe bundles.

PyInstaller packs Pillow, numpy, customtkinter and the Python runtime itself
into CoD4toSOF2.exe. All of them are permissive, so there is no restriction on
what the exe may be used for, but every one of those licences asks that its
text travels with the binary. This writes that file.

The texts are read out of the installed packages rather than typed in here, so
they are whatever the build machine actually bundled - right version, right
wording - instead of a copy that drifts. Run before PyInstaller so the .spec
can bundle the result too.

    python collect_licenses.py [THIRD-PARTY-LICENSES.txt]
"""
import os
import sys

# What the build pulls in. PyInstaller itself is a build tool and none of it
# ends up in the exe, so it is not listed; its bootloader is, and that is
# covered by PyInstaller's own GPL-with-exception, which is why the exception
# exists - see the note written at the end of the file.
BUNDLED = ["pillow", "numpy", "customtkinter"]
LICENCE_NAMES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "AUTHORS")


def _texts_for(dist):
    """Every licence-looking file shipped inside one installed distribution."""
    out = []
    try:
        files = list(dist.files or [])
    except Exception:
        files = []
    for f in files:
        name = os.path.basename(str(f)).upper()
        if not name.startswith(LICENCE_NAMES):
            continue
        if ".dist-info" not in str(f) and "/licenses/" not in str(f).replace("\\", "/"):
            continue
        try:
            out.append((str(f), dist.locate_file(f).read_text(encoding="utf-8",
                                                              errors="replace")))
        except Exception:
            continue
    return out


def collect():
    from importlib import metadata
    blocks, missing = [], []
    for name in BUNDLED:
        try:
            dist = metadata.distribution(name)
        except Exception:
            missing.append(name)
            continue
        meta = dist.metadata
        head = "%s %s" % (meta["Name"] or name, dist.version or "?")
        stated = (meta.get("License-Expression") or meta.get("License") or "").strip()
        if not stated or len(stated) > 200:          # some put the whole text here
            stated = ", ".join(c.rsplit("::", 1)[-1].strip()
                               for c in meta.get_all("Classifier") or []
                               if c.startswith("License ::")) or "see the text below"
        texts = _texts_for(dist)
        body = "\n\n".join("--- %s ---\n%s" % (os.path.basename(p), t.strip())
                           for p, t in texts)
        if not body:
            body = ("(this package ships no licence file in its metadata; it declares "
                    "%s - fetch the full text from the project's own repository)" % stated)
            missing.append(name + " (text)")
        blocks.append("=" * 78 + "\n%s - %s\n" % (head, stated) + "=" * 78 + "\n\n" + body)

    # The interpreter and standard library are bundled too.
    import sysconfig
    base = getattr(sys, "base_prefix", sys.prefix)
    cands = [os.path.join(base, "LICENSE.txt"),            # Windows installer
             os.path.join(base, "lib", "LICENSE.txt"),
             os.path.join(sysconfig.get_path("stdlib") or "", "LICENSE.txt"),
             os.path.join(base, "share", "doc", "python%d.%d" % sys.version_info[:2],
                          "copyright")]
    py = next((p for p in cands if p and os.path.isfile(p)), cands[0])
    head = "Python %s - Python Software Foundation License" % sys.version.split()[0]
    if os.path.isfile(py):
        with open(py, encoding="utf-8", errors="replace") as fh:
            blocks.append("=" * 78 + "\n%s\n" % head + "=" * 78 + "\n\n" + fh.read().strip())
    else:
        blocks.append("=" * 78 + "\n%s\n" % head + "=" * 78 +
                      "\n\n(LICENSE.txt was not found next to this Python; the text is at "
                      "https://docs.python.org/3/license.html)")
        missing.append("python (text)")
    return blocks, missing


HEADER = """Third-party licences for CoD4toSOF2.exe
=======================================

Generated by collect_licenses.py, which build_exe.bat runs before every build.
The texts below are read out of the packages installed on the machine that
built the exe, so they match the versions it actually contains. Do not edit
this file by hand - it is overwritten on the next build.

CoD4toSOF2 itself is MIT licensed - see LICENSE. The exe additionally contains
the packages below, bundled by PyInstaller. Every one of them is permissive:
none of them restricts what the exe may be used for, and they are reproduced
here because each asks that its licence text accompanies the binary.

Two things that are NOT in the exe and so are not listed:

  * q3map2 / NetRadiant. The compile step runs q3map2.exe as a separate
    program. No part of it is linked or copied into this tool, so its GPL
    does not extend here.
  * Call of Duty 4 assets. Nothing from the game ships with this tool. It
    reads an installation you already own and writes files for a map you
    convert yourself; redistributing those converted assets is a separate
    question and not one this licence answers.

PyInstaller's bootloader is compiled into the exe. PyInstaller is GPL with a
linking exception written for exactly this purpose, which permits distributing
the result under any licence.

"""


def main(argv):
    out = argv[1] if len(argv) > 1 else "THIRD-PARTY-LICENSES.txt"
    blocks, missing = collect()
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HEADER + "\n\n".join(blocks) + "\n")
    print("%s: %d component(s), %d bytes" % (out, len(blocks), os.path.getsize(out)))
    if missing:
        print("  WARNING: no licence text found for: %s" % ", ".join(missing))
        print("  Install them first (build_exe.bat does) or add the text by hand -")
        print("  do not ship the exe with a licence file that is missing a component.")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
